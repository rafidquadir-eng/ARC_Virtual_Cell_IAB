"""D4: per-dataset QC table and panel-coverage table -> reports/data_qc.md (+ reports/panel_coverage.csv).

A target counts as "measured" in a context when it is in that context's summary (>= 25 cells, and
for CRISPRi on-target remaining fraction <= 0.7); the >= 50-cell column applies the stricter cut.
Coverage is by cell line (`line` in loco.json): several datasets of one line count once.

  python scripts/data_qc.py --config loco.json --panel-file pert_counts.csv --meta reports/data_qc_meta.json
"""
import argparse
import json

import anndata as ad
import numpy as np
import pandas as pd


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="loco.json"); ap.add_argument("--panel-file", required=True)
    ap.add_argument("--meta", required=True, help="JSON {name: {cells, controls, licence, source}}")
    ap.add_argument("--out", default="reports/data_qc.md"); ap.add_argument("--cov-csv", default="reports/panel_coverage.csv")
    a = ap.parse_args()
    cfg = json.load(open(a.config)); meta = json.load(open(a.meta))
    panel = sorted(set(pd.read_csv(a.panel_file)["target_gene"].astype(str)) - {"non-targeting"})
    rows, by_line, by_line50 = [], {}, {}
    for c in cfg["contexts"]:
        z = np.load(c["summary"], allow_pickle=True)
        perts, nc = np.asarray(z["perts"], str), np.asarray(z["ncells"])
        inpanel = np.isin(perts, panel)
        line = c.get("line", c["name"])
        by_line.setdefault(line, set()).update(perts[inpanel])
        by_line50.setdefault(line, set()).update(perts[inpanel & (nc >= 50)])
        sub = ad.read_h5ad(c["h5ad"], backed="r")
        lab = sub.obs[c["pert_col"]].astype(str).values
        ctrl = lab == c["control"]
        idx = np.where(ctrl)[0][:5000]
        umi = float(np.median(np.asarray(sub.X[np.sort(idx)].sum(1)).ravel())) if len(idx) else float("nan")
        m = meta.get(c["name"], {})
        rows.append(dict(name=c["name"], line=line, library=c.get("library", ""), cells=m.get("cells", ""),
                         perts=len(perts), panel_measured=int(inpanel.sum()), panel_ge50=int((inpanel & (nc >= 50)).sum()),
                         genes_on_axis=int(z["present"].sum()), median_umi_ctrl_on_axis=round(umi),
                         median_kd=round(float(np.nanmedian(z["kd"])), 3), control_cells=m.get("controls", ""),
                         licence=m.get("licence", ""), source=m.get("source", "")))
    q = pd.DataFrame(rows)
    lines = sorted(by_line, key=lambda l: -len(by_line[l]))
    cov = pd.DataFrame({"target": panel})
    for l in lines:
        cov[l] = [("Y50" if t in by_line50[l] else "Y") if t in by_line[l] else "" for t in panel]
    cov["n_lines"] = cov[lines].ne("").sum(1); cov["n_lines_ge50"] = cov[lines].eq("Y50").sum(1)
    cov["lines"] = cov[lines].apply(lambda r: ";".join(l for l in lines if r[l]), axis=1)
    cov.to_csv(a.cov_csv, index=False)

    def counts(col):
        v = cov[col]
        return {"0": int((v == 0).sum()), "1": int((v == 1).sum()), "2": int((v == 2).sum()), ">=3": int((v >= 3).sum())}
    with open(a.out, "w") as f:
        f.write("# Data QC (curation D4)\n\n")
        f.write("Generated by `scripts/data_qc.py` from `loco.json`. *Measured* = in the context summary "
                "(>= 25 cells; CRISPRi on-target remaining fraction <= 0.7). Median UMI is over up to 5,000 control "
                "cells of the holdout subset, counted on the 18,533-gene challenge axis.\n\n## Per dataset\n\n")
        f.write(q.to_markdown(index=False) + "\n\n")
        f.write("## Panel coverage by cell line\n\n")
        f.write(f"Number of the {len(panel)} panel targets measured in N distinct lines:\n\n")
        f.write(pd.DataFrame({"measured (>=25 cells)": counts("n_lines"), ">= 50 cells": counts("n_lines_ge50")}).T.to_markdown() + "\n\n")
        f.write("Targets per line: " + ", ".join(f"{l} {len(by_line[l])} ({len(by_line50[l])} with >=50 cells)" for l in lines) + "\n\n")
        f.write(f"Per-target table (Y = measured, Y50 = measured with >= 50 cells); also `{a.cov_csv}`.\n\n")
        f.write(cov[["target"] + lines + ["n_lines"]].to_markdown(index=False) + "\n")
    print(q.to_string()); print(counts("n_lines"), counts("n_lines_ge50"))


if __name__ == "__main__":
    main()
